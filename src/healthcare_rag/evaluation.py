"""Toy-corpus evaluation for the BM25 baseline.

Usage:
    python -m healthcare_rag.evaluation index              # (re)build the toy BM25 index
    python -m healthcare_rag.evaluation run --markdown docs/baseline_results.md
"""

import argparse
import json
import math
import platform
import re
import statistics
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from healthcare_rag.baseline import BM25Baseline, Retriever
from healthcare_rag.bm25 import BM25Index, Document, client_from_settings
from healthcare_rag.config import get_settings
from healthcare_rag.gateway import GatewayClient

TOY_DIR = Path("eval/toy")
RECALL_KS = (1, 3, 5)
MRR_DEPTH = 10


@dataclass(frozen=True)
class Question:
    id: str
    question: str
    relevant: list[str]
    # Every group must match; within a group any alternative may match.
    answer_keywords: list[list[str]]


def load_corpus(path: Path) -> list[Document]:
    return [Document(**d) for d in json.loads(path.read_text(encoding="utf-8"))]


def load_questions(path: Path) -> list[Question]:
    return [Question(**q) for q in json.loads(path.read_text(encoding="utf-8"))]


def recall_at_k(ranked: list[str], relevant: list[str], k: int) -> float:
    return len(set(ranked[:k]) & set(relevant)) / len(relevant)


def reciprocal_rank(ranked: list[str], relevant: list[str]) -> float:
    for rank, doc_id in enumerate(ranked, start=1):
        if doc_id in relevant:
            return 1.0 / rank
    return 0.0


def keywords_match(answer: str, groups: list[list[str]]) -> bool:
    """True if every keyword group has an alternative that appears as a whole term.

    A plural suffix is allowed ("corticosteroid" matches "corticosteroids", "ssri" matches
    "SSRIs"), but substrings are not ("ics" does not match "antibiotics").
    """
    text = answer.lower()

    def found(term: str) -> bool:
        return re.search(rf"(?<!\w){re.escape(term.lower())}(?:e?s)?(?!\w)", text) is not None

    return all(any(found(alt) for alt in group) for group in groups)


def percentile(values: list[float], pct: float) -> float:
    """Nearest-rank percentile."""
    ordered = sorted(values)
    rank = max(1, math.ceil(pct / 100 * len(ordered)))
    return ordered[rank - 1]


def evaluate(
    questions: list[Question], retriever: Retriever, pipeline: BM25Baseline
) -> tuple[dict, list[dict]]:
    rows: list[dict] = []
    for q in questions:
        ranked = [h.id for h in retriever.search(q.question, k=MRR_DEPTH)]
        result = pipeline.answer(q.question)
        rows.append(
            {
                "id": q.id,
                "question": q.question,
                "ranked": ranked,
                "relevant": q.relevant,
                **{f"recall@{k}": recall_at_k(ranked, q.relevant, k) for k in RECALL_KS},
                "rr": reciprocal_rank(ranked, q.relevant),
                "answer": result.answer,
                "correct": keywords_match(result.answer, q.answer_keywords),
                "retrieval_s": result.retrieval_s,
                "generation_s": result.chat.latency_s,
                "total_s": result.retrieval_s + result.chat.latency_s,
                "prompt_tokens": result.chat.prompt_tokens,
                "completion_tokens": result.chat.completion_tokens,
                "cost_usd": result.chat.cost_usd,
                "backend": result.chat.backend,
                "cache": result.chat.cache,
            }
        )

    def col(name: str) -> list[float]:
        return [float(r[name]) for r in rows]

    summary = {
        "n": len(rows),
        **{f"recall@{k}": statistics.mean(col(f"recall@{k}")) for k in RECALL_KS},
        f"mrr@{MRR_DEPTH}": statistics.mean(col("rr")),
        "answer_accuracy": statistics.mean(col("correct")),
        **{
            f"{name}_p{p}": percentile(col(name), p)
            for name in ("retrieval_s", "generation_s", "total_s")
            for p in (50, 95)
        },
        "mean_prompt_tokens": statistics.mean(col("prompt_tokens")),
        "mean_completion_tokens": statistics.mean(col("completion_tokens")),
        "total_cost_usd": sum(col("cost_usd")),
    }
    return summary, rows


def to_markdown(summary: dict, rows: list[dict], meta: dict) -> str:
    ms = lambda s: f"{s * 1000:.0f} ms"  # noqa: E731
    lines = [
        "# BM25 baseline on the toy corpus",
        "",
        f"Measured {meta['date']}. Generated by `make eval-baseline`; do not edit by hand.",
        "",
        "## Setup",
        "",
        *(f"- **{k}:** {v}" for k, v in meta.items() if k != "date"),
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Questions (N) | {summary['n']} |",
        *(f"| Recall@{k} | {summary[f'recall@{k}']:.3f} |" for k in RECALL_KS),
        f"| MRR@{MRR_DEPTH} | {summary[f'mrr@{MRR_DEPTH}']:.3f} |",
        f"| Answer accuracy (keyword match) | {summary['answer_accuracy']:.3f} |",
        f"| Retrieval latency p50 / p95 | {ms(summary['retrieval_s_p50'])} / "
        f"{ms(summary['retrieval_s_p95'])} |",
        f"| Generation latency p50 / p95 | {ms(summary['generation_s_p50'])} / "
        f"{ms(summary['generation_s_p95'])} |",
        f"| End-to-end latency p50 / p95 | {ms(summary['total_s_p50'])} / "
        f"{ms(summary['total_s_p95'])} |",
        f"| Mean prompt / completion tokens | {summary['mean_prompt_tokens']:.0f} / "
        f"{summary['mean_completion_tokens']:.0f} |",
        f"| Total cost (gateway-reported) | ${summary['total_cost_usd']:.6f} |",
        "",
        "## Per question",
        "",
        "| ID | Rank of relevant doc | Correct | Total latency | Answer |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        rank = next((i for i, d in enumerate(r["ranked"], 1) if d in r["relevant"]), None)
        answer = " ".join(r["answer"].split()).replace("|", "\\|")
        lines.append(
            f"| {r['id']} | {rank or f'not in top {MRR_DEPTH}'} | "
            f"{'yes' if r['correct'] else 'no'} | {ms(r['total_s'])} | {answer} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    idx = sub.add_parser("index", help="(re)build the toy BM25 index")
    idx.add_argument("--corpus", type=Path, default=TOY_DIR / "corpus.json")
    run = sub.add_parser("run", help="run the baseline over the toy questions")
    run.add_argument("--questions", type=Path, default=TOY_DIR / "questions.json")
    run.add_argument("--k", type=int, default=3, help="passages given to the model")
    run.add_argument("--out", type=Path, default=Path("eval/results/baseline_bm25.json"))
    run.add_argument("--markdown", type=Path)
    run.add_argument("--hardware", default="", help="free-text hardware/power note")
    args = parser.parse_args(argv)

    settings = get_settings()
    index = BM25Index(client_from_settings(settings), settings.opensearch_index)

    if args.cmd == "index":
        docs = load_corpus(args.corpus)
        index.ensure_index(recreate=True)
        index.index_documents(docs)
        print(f"indexed {index.count()} documents into {settings.opensearch_index!r}")
        return

    gateway = GatewayClient.from_settings(settings)
    pipeline = BM25Baseline(index, gateway, k=args.k)
    questions = load_questions(args.questions)
    pipeline.answer("warm-up: what is metformin?")  # load the model; not measured
    summary, rows = evaluate(questions, index, pipeline)

    meta = {
        "date": datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"),
        "Retrieval": f"OpenSearch BM25 (english analyzer), index `{settings.opensearch_index}`, "
        f"{index.count()} documents",
        "Generation": f"`{settings.chat_model}` via the LLM Gateway at "
        f"`{settings.gateway_base_url}` (cache bypassed, temperature 0, max 256 tokens), "
        f"top {args.k} passages",
        "Answer accuracy": "every keyword group of the reference answer appears in the reply",
        "Latency": "client-side wall clock, sequential requests, after one warm-up request",
        "Host": f"{platform.system()} {platform.version()}, Python {platform.python_version()}",
        **({"Hardware": args.hardware} if args.hardware else {}),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        json.dumps({"meta": meta, "summary": summary, "rows": rows}, indent=2), encoding="utf-8"
    )
    print(json.dumps(summary, indent=2))
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(to_markdown(summary, rows, meta), encoding="utf-8")


if __name__ == "__main__":
    main()
